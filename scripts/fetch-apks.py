"""Downloads the currently approved apps into prebuilt/ so they ship in the ROM.

Run it before building:  python3 vendor/evox-apps/scripts/fetch-apks.py

It reads the published index, downloads every APK (skipping ones already
present), checks each SHA-256, and writes prebuilt/Android.bp and
prebuilt/products.mk so the APKs and a copy of the index end up in
/product/etc/evox-apps/. Without running it the ROM still builds, just with no
bundled apps, and the updater installs them from the internet instead.
"""

import hashlib
import json
import sys
import urllib.request
from pathlib import Path

INDEX_URL = "https://s3.msantoki.com/public/EvolutionX/apps/index.json"
OUT = Path(__file__).resolve().parent.parent / "prebuilt"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(url, dest):
    tmp = dest.with_suffix(".part")
    with urllib.request.urlopen(url, timeout=120) as r, open(tmp, "wb") as f:
        while chunk := r.read(1 << 20):
            f.write(chunk)
    tmp.rename(dest)


def module(name, src):
    return f"""prebuilt_etc {{
    name: "{name}",
    src: "{src}",
    filename: "{src}",
    sub_dir: "evox-apps",
    product_specific: true,
}}
"""


def main():
    OUT.mkdir(exist_ok=True)
    with urllib.request.urlopen(INDEX_URL, timeout=60) as r:
        index = json.load(r)

    names, bp, keep = [], ["// Generated by scripts/fetch-apks.py, do not edit\n"], {".gitignore"}
    for app in index["apps"]:
        name = app["url"].rsplit("/", 1)[1]
        dest = OUT / name
        if not dest.exists() or sha256(dest) != app["sha256"]:
            print(f"downloading {app['name']} {app['versionName']}")
            fetch(app["url"], dest)
        if sha256(dest) != app["sha256"]:
            dest.unlink()
            sys.exit(f"{name}: SHA-256 does not match the index")
        app["file"] = name
        mod = f"evox-apps_{app['id']}"
        bp.append(module(mod, name))
        names.append(mod)
        keep.add(name)
        print(f"ok {app['name']} {app['versionName']} ({app['build']})")

    (OUT / "index.json").write_text(json.dumps(index, indent=2))
    bp.append(module("evox-apps_index", "index.json"))
    names.append("evox-apps_index")
    keep.update({"index.json", "Android.bp", "products.mk"})

    (OUT / "Android.bp").write_text("\n".join(bp))
    (OUT / "products.mk").write_text(
        "# Generated by scripts/fetch-apks.py, do not edit\n"
        "PRODUCT_PACKAGES += \\\n" + " \\\n".join(f"    {n}" for n in names) + "\n")

    for f in OUT.iterdir():
        if f.name not in keep:
            f.unlink()
    print(f"{len(names) - 1} apps ready in {OUT}")


if __name__ == "__main__":
    main()
